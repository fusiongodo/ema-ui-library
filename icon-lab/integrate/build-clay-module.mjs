/* Builds lib/clay-icons.js: the approved clay renders and soft-solid glyphs, ready for the Studio theme (lib/cozy.js).

   node icon-lab/integrate/build-clay-module.mjs

   Clay: each icon-lab/blender/out/<id>/<id>-on-tile.png (1024 px, tile included) is downsized with macOS `sips` to 3× its
   largest display size and kept as lossless PNG, so the rendered colours stay exactly as approved. Glyphs: the SVG strings
   of icon-lab/glyphs/glyphs.mjs, drawn in currentColor. Both go in as text, so the bundle stays one self-contained file. */
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { GLYPHS } from "../glyphs/glyphs.mjs";

const LAB = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(LAB, "..", "lib", "clay-icons.js");

/* largest size in Studio (px): 44 = card-head tile, 54 = choice tile ("One item"), 52 = detail head (health/steps) */
const CLAY = {
  "protocol-pill": 54, "protocol-injection": 44, "log-scores": 44, "checkin-chat": 44, "wellbeing": 44,
  "pain": 44, "sleep": 44, "steps": 52, "calendar": 44, "guide": 44,
  "scores": 44, "dual-n-back": 44, "reaction": 44, "ask": 44,
};

const tmp = mkdtempSync(join(tmpdir(), "clay-"));
const clay = {};
try {
  for (const [id, px] of Object.entries(CLAY)) {
    const src = join(LAB, "blender", "out", id, `${id}-on-tile.png`), dst = join(tmp, `${id}.png`);
    execFileSync("sips", ["-Z", String(px * 3), src, "--out", dst], { stdio: "ignore" });
    clay[id] = "data:image/png;base64," + readFileSync(dst).toString("base64");
  }
} finally { rmSync(tmp, { recursive: true, force: true }); }
const glyph = Object.fromEntries(GLYPHS.map(g => [g.id, g.svg.replace(/^<svg /, '<svg aria-hidden="true" ')]));

const js = `/* ====== CLAY ICONS (Studio only) ======
   Generated by icon-lab/integrate/build-clay-module.mjs; do not edit by hand.
   clay: the Blender renders, tile included (3× their largest display size, PNG). glyph: the soft-solid glyphs (currentColor).
   Used by lib/cozy.js (studio pass); every other theme ignores it. */
const ClayIcons = {
  clay: {
${Object.entries(clay).map(([k, v]) => `    "${k}": "${v}",`).join("\n")}
  },
  glyph: {
${Object.entries(glyph).map(([k, v]) => `    "${k}": ${JSON.stringify(v)},`).join("\n")}
  },
};
`;
writeFileSync(OUT, js);
console.log(`wrote ${OUT} (${(js.length / 1024).toFixed(0)} KB)`);
