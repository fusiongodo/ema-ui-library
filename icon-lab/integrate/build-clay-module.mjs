/* Builds lib/clay-icons.js: the approved clay renders and soft-solid glyphs, ready for the Studio theme (lib/cozy.js).

   node icon-lab/integrate/build-clay-module.mjs

   Clay: each icon-lab/blender/out/<id>/<id>-on-tile.png (or the variant named in FILE; 1024 px, tile included) is downsized with macOS `sips` to 3× its
   largest display size and kept as lossless PNG, so the rendered colours stay exactly as approved; a clay not rendered yet is
   skipped with a note (Studio keeps its glyph there). Art: object renders without a
   tile (transparent PNG, e.g. out/week-box/week-box.png), downsized the same way to 3× their display box; a render that does not
   exist yet is skipped with a note, and Studio then keeps what it showed before. Glyphs: the SVG strings
   of icon-lab/glyphs/glyphs.mjs, drawn in currentColor; emblems: the statistical emblems of icon-lab/glyphs/stat-emblems.mjs, three styles each. Both go in as text, so the bundle stays one self-contained file. */
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { GLYPHS } from "../glyphs/glyphs.mjs";
import { STAT_EMBLEMS } from "../glyphs/stat-emblems.mjs";

const LAB = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(LAB, "..", "lib", "clay-icons.js");

/* largest size in Studio (px): 44 = card-head tile, 54 = choice tile ("One item"), 52 = detail head (health/steps) */
const CLAY = {
  "protocol-pill": 54, "protocol-injection": 44, "log-scores": 44, "checkin-chat": 44, "wellbeing": 44,
  "pain": 44, "sleep": 44, "steps": 52, "calendar": 44, "guide": 44,
  "scores": 44, "dual-n-back": 44, "reaction": 44, "ask": 44,
  "word-game": 44, "arithmetic": 44,
  "morning": 44, "noon": 44, "evening": 44, "fatigue": 44, "thirst": 44,
  "resting-heart": 52, "hrv": 52, "finding": 44, "flask": 44,
  "protocols-folder": 44,
};
/* a render other than <id>-on-tile.png: the approved variant (B for the three times of day) */
const FILE = { "morning": "morning-on-tile-b.png", "noon": "noon-on-tile-b.png", "evening": "evening-on-tile-b.png" };

/* object renders without a tile, by display box in Studio (px, width × height): the setup card on Protocols (week-box) and,
   closed, the status card after setup ("Today · all as planned", week-box-closed, the same box),
   the Apple Health card on Insights (health-watch, 86 px wide; the render is upright, 664 × 1024, so 133 high) */
const ART = { "week-box": { file: "week-box.png", w: 132, h: 80 }, "week-box-closed": { file: "week-box-closed.png", w: 132, h: 80 },
  "health-watch": { file: "health-watch.png", w: 86, h: 133 } };

const tmp = mkdtempSync(join(tmpdir(), "clay-"));
const clay = {}, art = {};
try {
  for (const [id, px] of Object.entries(CLAY)) {
    const src = join(LAB, "blender", "out", id, FILE[id] || `${id}-on-tile.png`), dst = join(tmp, `${id}.png`);
    if (!existsSync(src)) { console.log(`clay ${id}: ${src} not rendered yet, skipped`); continue; }
    execFileSync("sips", ["-Z", String(px * 3), src, "--out", dst], { stdio: "ignore" });
    clay[id] = "data:image/png;base64," + readFileSync(dst).toString("base64");
  }
  for (const [id, { file, w, h }] of Object.entries(ART)) {
    const src = join(LAB, "blender", "out", id, file), dst = join(tmp, `art-${id}.png`);
    if (!existsSync(src)) { console.log(`art ${id}: ${src} not rendered yet, skipped`); continue; }
    execFileSync("sips", ["-Z", String(Math.max(w, h) * 3), src, "--out", dst], { stdio: "ignore" });
    art[id] = "data:image/png;base64," + readFileSync(dst).toString("base64");
  }
} finally { rmSync(tmp, { recursive: true, force: true }); }
const glyph = Object.fromEntries(GLYPHS.map(g => [g.id, g.svg.replace(/^<svg /, '<svg aria-hidden="true" ')]));
/* statistical emblems: three styles each (a, b, c), shown one at a time by data-emblem on the phone frame (lib/studio.css) */
const emblem = Object.fromEntries(STAT_EMBLEMS.map(e => [e.id, Object.fromEntries(Object.entries(e.svg).map(([v, s]) => [v, s.replace(/^<svg /, '<svg aria-hidden="true" ')]))]));

const js = `/* ====== CLAY ICONS (Studio only) ======
   Generated by icon-lab/integrate/build-clay-module.mjs; do not edit by hand.
   clay: the Blender renders, tile included (3× their largest display size, PNG). art: object renders without a tile
   (transparent PNG, 3× their display box). glyph: the soft-solid glyphs (currentColor). emblem: the statistical emblems
   (stat-*), each in three styles a, b, c (explicit colours; lib/studio.css shows the one data-emblem picks).
   Used by lib/cozy.js (studio pass); every other theme ignores it. */
const ClayIcons = {
  clay: {
${Object.entries(clay).map(([k, v]) => `    "${k}": "${v}",`).join("\n")}
  },
  art: {
${Object.entries(art).map(([k, v]) => `    "${k}": "${v}",`).join("\n")}
  },
  glyph: {
${Object.entries(glyph).map(([k, v]) => `    "${k}": ${JSON.stringify(v)},`).join("\n")}
  },
  emblem: {
${Object.entries(emblem).map(([k, v]) => `    "${k}": ${JSON.stringify(v)},`).join("\n")}
  },
};
`;
writeFileSync(OUT, js);
console.log(`wrote ${OUT} (${(js.length / 1024).toFixed(0)} KB)`);
